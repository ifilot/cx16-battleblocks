"""Bundle graphics and bank-aligned audio without changing the asset generators."""
from pathlib import Path
import re

from package_game import GRAPHICS_FILES

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'src'


def graphics_bundle():
    data = bytearray()
    entries = []
    for name in GRAPHICS_FILES:
        asset = (SRC / name).read_bytes()
        if not 0 < len(asset) <= 65535:
            raise ValueError(f'Invalid graphics size: {name}')
        entries.append((name.lower(), len(data), len(asset)))
        data.extend(asset)
    return data, entries


def audio_bundle():
    # Preserve the bank assignments generated by the external sound project.
    header = (SRC / 'music.h').read_text()
    tracks = re.findall(r'#define MUSIC_\w+_FILE "([^"]+)"\s+#define MUSIC_\w+_BANK (\d+)', header)
    if not tracks:
        raise ValueError('No music bank definitions found')
    effects = re.search(r'#define SFX_BANK_FILE "([^"]+)"', (SRC / 'sfx.h').read_text()).group(1)
    assets = [(effects, 2)] + [(name, int(bank)) for name, bank in tracks]
    data = bytearray()
    for name, bank in sorted(assets, key=lambda item: item[1]):
        offset = (bank - 2) * 8192
        if offset < len(data):
            raise ValueError(f'Overlapping audio banks: {name}')
        data.extend(bytes(offset - len(data)))
        data.extend((SRC / name.upper()).read_bytes())
    if len(data) > 62 * 8192:
        raise ValueError('Audio exceeds the standard 512 KB RAM')
    return data


def main():
    data, entries = graphics_bundle()
    (SRC / 'GRAPHICS.DAT').write_bytes(data)
    (SRC / 'AUDIO.BIN').write_bytes(audio_bundle())
    header = '/* Generated by tools/bundle_resources.py. */\n'
    for i, (name, _, _) in enumerate(entries):
        symbol = name.upper().replace('-', '_').replace('.', '_')
        header += f'#define RES_{symbol} {i}\n'
    header += '#ifdef RESOURCE_TABLE\nstatic const struct { unsigned long offset; unsigned int size; } graphics[] = {\n'
    header += ''.join(f'    {{{offset}UL, {size}U}},\n' for name, offset, size in entries)
    header += '};\n#endif\n'
    (SRC / 'resources_generated.h').write_text(header)


if __name__ == '__main__':
    main()
