"""Bake approved native banners into free VRAM on either side of the maps.

Each theme has one atlas shared by PLAYER 1/2 and COMPUTER 1/2. The tiny maps
select complete banners, so changing game mode requires no pixel drawing.
"""
import json
from PIL import Image
import nameplate_art as design
from computer_art import icon

ROOT = design.ROOT
SPILL_FIRST = 448  # $1C000: after the gameplay maps, before the title map.


def build():
    maps = []
    counts = []
    first = 130 + len((ROOT / 'src/HUD.DAT').read_bytes()) // 256
    primary_capacity = 368 - first
    assert primary_capacity >= 0, 'HUD overlaps Cyberpunk wallpaper'
    for style, cyber, filename in (('arcade', False, 'NAME-L.DAT'),
                                   ('cyberpunk', True, 'NAME-C.DAT'),
                                   ('foundry', False, 'NAME-F.DAT'), ('synthwave', True, 'NAME-S.DAT'), ('matrix', True, 'NAME-M.DAT')):
        palette = [tuple(c) for c in json.loads((design.PALETTE_DIR / (style + '.json')).read_text())]
        indices = {}
        for index, color in enumerate(palette[1:], 1):
            indices.setdefault(color, index)
        foundry = style == 'foundry'
        synthwave = style in ('synthwave', 'matrix')
        icon_palette = palette.copy()
        if synthwave:
            icon_palette[147] = palette[244]
        icons = [design.controller(icon_palette, cyber), icon(palette, style, 2)]
        # The menu's 2x2 computer face leads the atlas, outside the logo's spill.
        face = Image.new('RGBA', (32, 32))
        face.paste(icons[1], (0, 4), icons[1])
        pixels = bytes(indices[p[:3]] if p[3] else 0 for p in face.getdata())
        tiles = [b''.join(pixels[(ty * 16 + y) * 32 + tx * 16:(ty * 16 + y) * 32 + tx * 16 + 16]
                          for y in range(16)) for ty in range(2) for tx in range(2)]
        cache, variants = {}, []
        for computer in (False, True):
            for number in (1, 2):
                image = Image.new('RGBA', (320, 32))
                label = ('COMPUTER ' if computer else 'PLAYER ') + str(number)
                design.nameplate(image, palette, cyber, 0, icons[computer], label,
                                 'CPU' if computer else 'HUMAN', foundry=foundry, synthwave=synthwave)
                pixels = bytes(indices[p[:3]] if p[3] else 0 for p in image.getdata())
                rows = []
                for ty in range(2):
                    row = []
                    for tx in range(1, 19):
                        tile = b''.join(pixels[(ty * 16 + y) * 320 + tx * 16:
                                             (ty * 16 + y) * 320 + tx * 16 + 16]
                                        for y in range(16))
                        if tile not in cache:
                            number = len(tiles)
                            cache[tile] = (first + number if number < primary_capacity else
                                           SPILL_FIRST + number - primary_capacity)
                            tiles.append(tile)
                        row.append(cache[tile])
                    rows.append(row)
                variants.append(rows)
        assert len(tiles) <= primary_capacity + 32, 'Banners overlap the title map'
        (ROOT / 'src' / filename).write_bytes(b''.join(tiles[:primary_capacity]))
        (ROOT / 'src' / filename.replace('.DAT', 'X.DAT')).write_bytes(b''.join(tiles[primary_capacity:]))
        maps.append(variants)
        counts.append(len(tiles))
    header = '/* Generated by assets/scripts/build_nameplates.py; native approved banners. */\n'
    header += f'#define BANNER_TILE_FIRST {first}\n#define BANNER_TILE_SPILL {SPILL_FIRST}\n'
    header += '/* Computer face: two rows of two tiles from BANNER_TILE_FIRST. */\n'
    assert first >= 256 and SPILL_FIRST + 32 <= 512, 'Banner tiles must share bank one'
    header += '/* Tile low bytes; all banners use tile bank one. */\n'
    header += 'static const uint8_t banner_map[5][4][2][18] = {\n'
    for theme in maps:
        header += '    {\n'
        for variant in theme:
            header += '        {' + ', '.join('{' + ', '.join((str(tile & 255) for tile in row)) + '}' for row in variant) + '},\n'
        header += '    },\n'
    header += '};\n'
    (ROOT / 'src/banner_generated.h').write_text(header)
    print(f'Nameplates: {counts} tiles; first {primary_capacity} at {first}, remainder at {SPILL_FIRST}')


if __name__ == '__main__':
    build()
