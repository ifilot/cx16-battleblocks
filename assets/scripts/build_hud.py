"""Bake split cards into native 8bpp tiles; reserve writable numeric tiles.

Static artwork is deduplicated. Each tile touched by a changing value has its
own storage, so a counter can be redrawn without changing another HUD field.
"""
from pathlib import Path
from PIL import Image
import hud_art as hud

ROOT=hud.ROOT
# x, y, width, height, scale, background (palette index)
FIELDS=[(158,53,118,14,2,30),(109,96,29,7,1,30),(249,96,29,7,1,30)]
FIELDS += [(279,265+i*16,29,7,1,30) for i in range(7)]
FIELDS += [(279,406+i*12,29,7,1,30) for i in range(4)]


def build():
    hud.ICONS=hud.load_icons()
    c=hud.Canvas(Image.new('RGB',(640,480),(0,0,0)))
    for offset in (0,320):
        x=16+offset
        c.panel(x,32,272,40,hud.PAPER,bevel=True)
        c.draw.rectangle((x+1,33,x+270,48),fill=hud.TEAL)
        c.text('SCORE',x+8,38,hud.WHITE)
        for dx,label,w in ((0,'LEVEL',132),(136,'LINES',136)):
            c.panel(x+dx,78,w,30,hud.PAPER,bevel=True)
            c.draw.rectangle((x+dx+1,79,x+dx+w-2,90),fill=hud.TEAL)
            c.text(label,x+dx+8,82,hud.WHITE)
        # The leftmost card tile shares a tile-map cell with the field rim.
        # Preserve that rim and its shadow in the composite tile.
        c.draw.rectangle((176+offset,240,177+offset,449),fill=(0,0,0))
        # Palette zero is transparent, so use the opaque black duplicate.
        # Conversion below assigns black on this rim to index 16 explicitly.
        c.draw.rectangle((178+offset,240,179+offset,451),fill=hud.INK)
        c.draw.rectangle((176+offset,450,177+offset,451),fill=hud.INK)
        sx=184+offset
        c.panel(sx,240,132,140,hud.PAPER,bevel=True)
        c.panel(sx,386,132,70,hud.PAPER,bevel=True)
        c.draw.rectangle((sx+1,241,sx+130,257),fill=hud.TEAL)
        c.draw.rectangle((sx+1,387,sx+130,401),fill=hud.TEAL)
        c.text('PIECES',sx+10,246,hud.WHITE)
        c.text('CLEARS',sx+10,391,hud.WHITE)
        for i in range(7): c.icon(i,sx+10,262+i*16)
        for i,label in enumerate(('SINGLE','DOUBLE','TRIPLE','FOUR')):
            c.text(label,sx+10,406+i*12,hud.INK)
    palette=hud.get_color_palette()
    # First occurrence wins (black index zero is transparent).
    indices={}
    for i,col in enumerate(palette): indices.setdefault(tuple(int(v) for v in col),i)
    pixels=bytearray(indices[col] for col in c.image.getdata())
    # Black inside cards is opaque; black outside the HUD is transparent.
    for offset in (0,320):
        for x,y,w,h in ((16,32,272,40),(16,78,132,30),(152,78,136,30),(184,240,132,140),(184,386,132,70)):
            for py in range(y,y+h):
                for px in range(x+offset,x+offset+w):
                    index=py*640+px
                    if pixels[index]==0: pixels[index]=16
    for offset in (0,320):
        for y in range(240,450):
            for x in (176+offset,177+offset): pixels[y*640+x]=16
    # Give shadows their own palette role, independent of cyan text/rims.
    for offset in (0,320):
        for x,y,w,h in ((16,32,272,40),(16,78,132,30),(152,78,136,30),(184,240,132,140),(184,386,132,70)):
            for py in range(y+2,y+h+2):
                for px in range(x+offset+2,x+offset+w+2):
                    if px >= x+offset+w or py >= y+h:
                        if pixels[py*640+px] == 11: pixels[py*640+px] = 239
        for y in range(240,452):
            for x in (178+offset,179+offset): pixels[y*640+x]=239
        for y in (450,451):
            for x in (176+offset,177+offset): pixels[y*640+x]=239
    writable=set()
    for offset in (0,320):
        for x,y,w,h,_,_ in FIELDS:
            for ty in range(y//16,(y+h-1)//16+1):
                for tx in range((x+offset)//16,(x+offset+w-1)//16+1): writable.add((tx,ty))
    tiles=[];cache={};tilemap=[]
    for ty in range(30):
        row=[]
        for tx in range(40):
            tile=b''.join(pixels[(ty*16+y)*640+tx*16:(ty*16+y)*640+tx*16+16] for y in range(16))
            if (tx,ty) not in writable and not any(tile): row.append(0);continue
            if (tx,ty) in writable or tile not in cache:
                number=130+len(tiles);tiles.append(tile)
                if (tx,ty) not in writable:cache[tile]=number
            else:number=cache[tile]
            row.append(number)
        tilemap.append(row)
    assert 130+len(tiles)<=368, 'HUD must end before Cyberpunk tiles at $17000'
    (ROOT/'src/HUD.DAT').write_bytes(b''.join(tiles))
    header='/* Generated by assets/scripts/build_hud.py; native split-card HUD. */\n'
    header+='struct HudField { uint16_t x, y; uint8_t width, height, scale, background; };\n'
    header+='static const struct HudField hud_fields[14] = {\n'+''.join('    {'+', '.join(map(str,f))+'},\n' for f in FIELDS)+'};\n'
    header+='/* Zero is transparent; other entries are tile IDs minus 129. */\n'
    header+='static const uint8_t hud_map[30][40] = {\n'+''.join('    {'+', '.join(str(t-129 if t else 0) for t in r)+'},\n' for r in tilemap)+'};\n'
    header+='static const uint8_t hud_digits[10][7][5] = {\n'
    for digit in range(10):
        rows=['{'+', '.join('11' if bit=='1' else '30' for bit in bits)+'}' for bits in hud.FONT[str(digit)]]
        header+='    {'+', '.join(rows)+'},\n'
    header+='};\n'
    (ROOT/'src/hud_generated.h').write_text(header)
    print(f'HUD: {len(tiles)} native tiles, last tile {129+len(tiles)}, {len(writable)} writable cells')

if __name__=='__main__': build()
