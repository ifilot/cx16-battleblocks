"""Bake the splash lettering into a transparent, themed menu title.

Menu tiles reuse $1C000..$1EFFF while gameplay banners and the splash are
inactive. The atlas must stop before the resident loading glyph at $1F000.
Palette entries 246..249 are reserved for its two faces, outline and shadow.
"""
from pathlib import Path

from render_splash import Canvas

ROOT = Path(__file__).resolve().parents[2]
FIRST = 448
WIDTH, HEIGHT = 320, 32


def build():
    canvas = Canvas(['000000'] * 8)
    # The same 5x7 lettering, outline and offset shadow as the splash.
    canvas.text('BATTLE', 76, 1, 4, 246, stroke=1, shadow=1)
    canvas.text('BLOCKS', 244, 1, 4, 247, stroke=1, shadow=1)
    image = canvas.image.crop((0, 0, WIDTH, HEIGHT))
    # Canvas uses index zero for its stroke and shadow; distinguish these
    # opaque pixels from the transparent area with explicit masks.
    mask = Canvas(['000000'] * 8)
    mask.text('BATTLE', 76, 1, 4, 1, stroke=0)
    mask.text('BLOCKS', 244, 1, 4, 1, stroke=0)
    from PIL import Image, ImageFilter
    face = Image.frombytes('L', (WIDTH, HEIGHT),
                           mask.image.crop((0, 0, WIDTH, HEIGHT)).tobytes())
    outline = face.filter(ImageFilter.MaxFilter(3))
    shadow = Image.new('L', (WIDTH, HEIGHT))
    shadow.paste(outline, (1, 1))
    pixels = bytearray(image.getdata())
    for i, (edge, shade) in enumerate(zip(outline.getdata(), shadow.getdata())):
        if pixels[i] == 0:
            pixels[i] = 248 if edge else 249 if shade else 0
    tiles, cache, rows = [], {}, []
    for ty in range(HEIGHT // 16):
        row = []
        for tx in range(WIDTH // 16):
            tile = b''.join(pixels[(ty * 16 + y) * WIDTH + tx * 16:
                                  (ty * 16 + y) * WIDTH + tx * 16 + 16]
                            for y in range(16))
            if not any(tile):
                row.append(0)
                continue
            if tile not in cache:
                cache[tile] = FIRST + len(tiles)
                tiles.append(tile)
            row.append(cache[tile])
        rows.append(row)
    assert FIRST + len(tiles) <= 496, 'Menu title overlaps the loading glyph'
    (ROOT / 'src/MENU.DAT').write_bytes(b''.join(tiles))
    rainbow = (255, 227, 199, 157, 142, 87, 8, 58)
    arcade = [bytearray(tile) for tile in tiles]
    for ty, row in enumerate(rows):
        for tile in row:
            if not tile:
                continue
            for y in range(16):
                color = rainbow[min(7, max(0, ty * 16 + y - 1) * 8 // 28)]
                for x in range(16):
                    if arcade[tile - FIRST][y * 16 + x] in (246, 247):
                        arcade[tile - FIRST][y * 16 + x] = color
    (ROOT / 'src/MENU-A.DAT').write_bytes(b''.join(arcade))
    header = '/* Generated by assets/scripts/build_menu_title.py; splash-style menu lettering. */\n'
    header += f'#define MENU_TITLE_FIRST {FIRST}\n'
    header += 'static const uint8_t menu_title_map[2][20] = {\n'
    header += ''.join('    {' + ', '.join(str(tile & 255) for tile in row) + '},\n' for row in rows)
    header += '};\n'
    (ROOT / 'src/menu_title_generated.h').write_text(header)
    print(f'Menu title: {len(tiles)} transparent tiles at {FIRST}')


if __name__ == '__main__':
    build()
